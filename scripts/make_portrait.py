def generate_ascii_svg(output_path="ascii.svg"):
    lines = ASCII_ART.split("\n")

    # Parâmetros de dimensão e espaçamento proporcional (JetBrains Mono/Monospace)
    font_size = 7
    line_spacing = 8.5
    char_width = 4.3

    max_cols = max(len(line) for line in lines)
    width = int(max_cols * char_width + 10)
    height = int(len(lines) * line_spacing + 10)

    # Intervalo de tempo por linha (35 milissegundos para efeito fluido)
    delay_step = 0.035

    svg_header = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
  <style>
    text {{
      font-family: 'JetBrains Mono', 'Courier New', monospace;
      font-size: {font_size}px;
      white-space: pre;
      fill: #1f2328;
    }}
    @media (prefers-color-scheme: dark) {{
      text {{ fill: #f0f6fc; }}
    }}
  </style>
  <g id="ascii-portrait">
"""

    svg_body = []
    for i, line in enumerate(lines):
        y = round(10 + i * line_spacing, 2)
        begin_time = round(0.05 + i * delay_step, 3)
        # Escapa caracteres XML reservados (<, >, &, ")
        escaped_line = html.escape(line)

        text_node = (
            f'    <text x="5" y="{y}" visibility="hidden">{escaped_line}'
            f'<set attributeName="visibility" from="hidden" to="visible" begin="{begin_time}s" fill="freeze" />'
            f"</text>"
        )
        svg_body.append(text_node)

    svg_footer = """  </g>
</svg>
"""

    full_svg = svg_header + "\n".join(svg_body) + "\n" + svg_footer

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(full_svg)

    print(
        f"✅ {output_path} gerado com sucesso! ({len(lines)} linhas animadas)"
    )


if __name__ == "__main__":
    generate_ascii_svg()